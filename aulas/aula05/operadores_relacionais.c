#include <stdio.h>


int main(){
// == igualdade
// != diferença
// < menor
// > maior
// >= maior ou igual
// <= menor ou igual

    printf(" 2 == 5? %i\n", 2 == 5);
    printf(" 2 != 5? %i\n", 2 != 5);
    printf(" 2 < 5? %i\n", 2 < 5);
    printf(" 2 <= 5? %i\n", 2 <= 5 );
    printf(" 2 > 5? %i\n", 2 > 5);
    printf(" 2 >= 5? %i\n", 2 >= 5);




    return 0;
}